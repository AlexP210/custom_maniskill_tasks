"""Regenerate `fr3.urdf` and `meshes/` from Franka's `franka_description` (Apache-2.0).

Not run at import or at runtime -- the outputs are committed, so using the FR3 needs neither xacro
nor a franka_description checkout. Only needed to rebuild them:

    # 1. expand the xacro (any xacro >= 2 with `$(find franka_description)` resolving to the checkout)
    xacro <franka_description>/robots/fr3/fr3.urdf.xacro hand:=true -o fr3_raw.urdf
    # 2. clean it up and convert the meshes
    python build_fr3_assets.py fr3_raw.urdf <franka_description>

What it changes relative to the raw expansion, and why:
  * drops the `base` link and the accelerometer links: ManiSkill wants `fr3_link0` as the root, and
    nothing reads the accelerometers;
  * rewrites `package://franka_description/...` mesh paths to paths relative to this directory;
  * converts the visual `.dae` meshes to `.glb` (a 26 MB -> small repo cost, and the format
    ManiSkill's own Panda uses); collision `.stl` meshes are copied as they are;
  * adds `fr3_leftfinger_pad` / `fr3_rightfinger_pad` links 0.0455 m along each finger, as in
    ManiSkill's `panda_v2.urdf`, so the Panda grasp logic's frames exist under FR3 names.
"""

from __future__ import annotations

import re
import shutil
import sys
from pathlib import Path

import trimesh

HERE = Path(__file__).resolve().parent
PACKAGE = "package://franka_description/"

PAD_LINKS = """  <link name="fr3_{side}finger_pad"/>
  <joint name="fr3_{side}finger_pad_joint" type="fixed">
    <origin rpy="0 0 0" xyz="0 0 0.0455"/>
    <parent link="fr3_{side}finger"/>
    <child link="fr3_{side}finger_pad"/>
  </joint>
"""


def _drop(urdf: str, tag: str, name_pattern: str) -> str:
    """Remove every <link>/<joint> element whose name matches `name_pattern`."""
    element = rf"\s*<{tag} name=\"(?:{name_pattern})\"[^>]*?(?:/>|>.*?</{tag}>)"
    return re.sub(element, "", urdf, flags=re.S)


def main(raw_urdf: Path, franka_description: Path) -> None:
    urdf = raw_urdf.read_text()
    # xacro's "autogenerated from <absolute path>" banner would put the builder's home directory in the repo
    urdf = re.sub(r"<!-- =+ -->.*?<!-- =+ -->\n", "", urdf, count=1, flags=re.S)

    urdf = _drop(urdf, "joint", r"fr3_base_joint|fr3_link\d_accelerometer_\w+_joint")
    urdf = _drop(urdf, "link", r"base|fr3_link\d_accelerometer_\w+")

    meshes = HERE / "meshes"
    shutil.rmtree(meshes, ignore_errors=True)
    for match in sorted(set(re.findall(rf'{re.escape(PACKAGE)}([^"]+)', urdf))):
        source = franka_description / match
        target = meshes / Path(match).relative_to("meshes")
        target.parent.mkdir(parents=True, exist_ok=True)
        if source.suffix == ".dae":
            target = target.with_suffix(".glb")
            scene = trimesh.load(source, force="scene")
            scene.export(target)
        else:
            shutil.copy(source, target)
        urdf = urdf.replace(f"{PACKAGE}{match}", "meshes/" + str(target.relative_to(meshes)))

    # the pad links go in before the finger links, like panda_v2.urdf
    for side in ("left", "right"):
        urdf = urdf.replace(
            f'  <link name="fr3_{side}finger">', PAD_LINKS.format(side=side) + f'  <link name="fr3_{side}finger">'
        )
    assert "package://" not in urdf and "accelerometer" not in urdf

    (HERE / "fr3.urdf").write_text(urdf)
    for name in ("LICENSE", "NOTICE"):
        shutil.copy(franka_description / name, HERE / f"{name}.franka_description")
    print(f"wrote {HERE / 'fr3.urdf'} and {sum(1 for _ in meshes.rglob('*') if _.is_file())} meshes")


if __name__ == "__main__":
    main(Path(sys.argv[1]), Path(sys.argv[2]))
